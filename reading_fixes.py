# ── figures.json から人物名読み辞書を構築
def _load_figures_dict():
    path = os.path.join(_DIR, 'figures.json')
    if not os.path.exists(path):
        return {}
    with open(path, encoding='utf-8') as f:
        data = json.load(f)
    out = {}
    for fid, f_obj in data.items():
        name = f_obj.get('name', '').strip()
        kana = f_obj.get('kana', '').strip()
        if not name or not kana:
            continue
        # かな部分のみ抽出（カッコ書き等は捨てる）
        kana = re.sub(r'[（(].*?[）)]', '', kana)
        if not kana:
            continue
        out[name] = _kata(kana)
    return out

# ── spots.json からスポット名読み辞書を構築（4字以上の固有名のみ）
def _load_spots_dict():
    path = os.path.join(_DIR, 'spots.json')
    if not os.path.exists(path):
        return {}
    with open(path, encoding='utf-8') as f:
        data = json.load(f)
    out = {}
    for sid, s in data.items():
        name = s.get('name', '').strip()
        kana = s.get('kana', '').strip()
        if not name or not kana:
            continue
        # カッコ書き除去
        clean_name = re.sub(r'[（(].*?[）)]', '', name).strip()
        clean_kana = re.sub(r'[（(].*?[）)]', '', kana).strip()
        if len(clean_name) < 4:
            continue
        if not clean_kana:
            continue
        out[clean_name] = _kata(clean_kana)
    return out

# ── 統合辞書を構築（長い文字列順に並べる）
_FIGURES = _load_figures_dict()
_SPOTS = _load_spots_dict()

# 統合（優先：手動 > スポット > 人物）
_combined = {}
_combined.update(_FIGURES)
_combined.update(_SPOTS)
_combined.update(MANUAL_FIXES)

# 長い文字列から順に置換（部分一致誤置換を防ぐ）
READING_FIXES = sorted(_combined.items(), key=lambda x: -len(x[0]))

def fix_reading(text):
    """テキスト内の固有名詞を読み仮名（カタカナ）に置換"""
    for kanji, yomi in READING_FIXES:
        text = text.replace(kanji, yomi)
    return text

